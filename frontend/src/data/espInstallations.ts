function shiftIsoDate(value: string, dayDelta: number): string {
  const date = new Date(value)
  date.setDate(date.getDate() + dayDelta)
  return date.toISOString().slice(0, 10)
}

export function buildEspInstallationPeriods(wellId: string, data: TimeSeriesPoint[]): EspInstallationPeriod[] {
  const changes = espInstallationChangesByWell[wellId] ?? []
  const chartStart = data[0]?.date
  const chartEnd = data[data.length - 1]?.date

  if (!chartStart || !chartEnd || changes.length === 0) {
    return []
  }

  return changes.flatMap((change, index) => {
    const nextChange = changes[index + 1]
    const rawStartDate = change.date
    const rawEndDate = nextChange ? shiftIsoDate(nextChange.date, -1) : chartEnd

    if (rawEndDate < chartStart || rawStartDate > chartEnd) {
      return []
    }

    const startDate = rawStartDate < chartStart ? chartStart : rawStartDate
    const endDate = rawEndDate > chartEnd ? chartEnd : rawEndDate

    if (endDate < startDate) {
      return []
    }

    return [
      {
        id: `esp-${wellId}-${index}-${change.date}`,
        espId: change.espId,
        startDate,
        endDate
      }
    ]
  })
}

export function hasEspInstallationData(wellId: string): boolean {
  return Boolean(espInstallationChangesByWell[wellId]?.length)
}
